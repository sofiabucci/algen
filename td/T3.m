function r = T3(b,c,D,popSize,maxGen,seed)
% T3
% Comparacao entre:
%   - Metodo de Lagrange
%   - Algoritmo Genetico do MATLAB
%   - Algoritmo Genetico Proprio
%
% O objetivo e validar o algoritmo desenvolvido
% comparando os resultados com a solucao analitica.

%% Valores por defeito

if nargin == 0

    d = dados_grupo12();

    b = d.b;
    c = d.c;
    D = d.D;

    popSize = 50;
    maxGen = 100;
    seed = 1;

end

%% Limites

d = dados_grupo12();

Pmin = d.Pmin;
Pmax = d.Pmax;

%% Resolver por Lagrange

L = Lagrange( ...
    b,c,D,...
    Pmin,Pmax,...
    []);

%% Resolver por GA MATLAB

G = GA( ...
    b,c,D,...
    popSize,...
    maxGen,...
    seed,...
    Pmin,...
    Pmax,...
    []);

%% Resolver por GA Próprio

GP = GAProprio( ...
    b,c,D,...
    popSize,...
    maxGen,...
    seed,...
    Pmin,...
    Pmax);

%% Guardar resultados

r.Lagrange = L;

r.GA = G;

r.GAProprio = GP;

%% Erros relativamente ao método analítico

r.erroPotenciaGA = ...
    norm(L.P - G.P);

r.erroPotenciaGAProprio = ...
    norm(L.P - GP.P);

r.erroCustoGA = ...
    abs(L.C - G.C);

r.erroCustoGAProprio = ...
    abs(L.C - GP.C);

r.erroRelativoGA = ...
    100*abs(L.C-G.C)/L.C;

r.erroRelativoGAProprio = ...
    100*abs(L.C-GP.C)/L.C;

%% Comparação principal

r.tabelaComparacao = table( ...
    [L.P(1); G.P(1); GP.P(1)], ...
    [L.P(2); G.P(2); GP.P(2)], ...
    [L.C; G.C; GP.C], ...
    [L.lambdaSystem; ...
     G.lambdaSystem; ...
     GP.lambdaSystem], ...
    'RowNames', ...
    {'Lagrange', ...
     'GA_MATLAB', ...
     'GA_Proprio'}, ...
    'VariableNames', ...
    {'P1', ...
     'P2', ...
     'Custo', ...
     'LambdaSistema'});

%% Comparação dos erros

r.tabelaErros = table( ...
    [r.erroPotenciaGA;
     r.erroPotenciaGAProprio], ...
    [r.erroCustoGA;
     r.erroCustoGAProprio], ...
    [r.erroRelativoGA;
     r.erroRelativoGAProprio], ...
    'RowNames', ...
    {'GA_MATLAB', ...
     'GA_Proprio'}, ...
    'VariableNames', ...
    {'ErroPotencia', ...
     'ErroCusto', ...
     'ErroRelativoPercent'});

%% Apresentação

fprintf('\n');
fprintf('====================================\n');
fprintf('T3 - COMPARACAO DOS METODOS\n');
fprintf('====================================\n');

fprintf('\nRESULTADOS\n\n');

disp(r.tabelaComparacao);

fprintf('\nERROS RELATIVOS AO LAGRANGE\n\n');

disp(r.tabelaErros);

fprintf('\nESTATISTICAS GA PROPRIO\n');

fprintf('Melhor custo  : %.6f\n',GP.melhor);

fprintf('Media custo   : %.6f\n',GP.media);

fprintf('Pior custo    : %.6f\n',GP.pior);

fprintf('Desvio padrao : %.6f\n',GP.desvioPadrao);

end